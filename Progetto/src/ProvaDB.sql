--  DDL for Trigger TRG_CONTROLLO_CAMBIO_PROPRIETARIO
--------------------------------------------------------

  CREATE OR REPLACE NONEDITIONABLE TRIGGER "OOBD16"."TRG_CONTROLLO_CAMBIO_PROPRIETARIO" 
BEFORE UPDATE OF emailProprietario ON Gruppo
FOR EACH ROW
DECLARE
    v_is_membro NUMBER;
BEGIN
    -- Conta se il nuovo proprietario fa già parte del gruppo con invito accettato (statoInvito = 1)
    SELECT COUNT(*)
    INTO v_is_membro
    FROM PartecipazioneGruppo
    WHERE idGruppo = :NEW.idGruppo 
      AND emailUtente = :NEW.emailProprietario
      AND statoInvito = 1;

    -- Se il conteggio è 0, blocca l'operazione
    IF v_is_membro = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20002, 
            'Violazione Vincolo: Impossibile nominare ' || :NEW.emailProprietario || 
            ' come proprietario del gruppo #' || :NEW.idGruppo || 
            ' perché non è un membro attivo!'
        );
    END IF;
END;
/
