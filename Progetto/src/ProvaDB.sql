--  DDL for Trigger TRG_DEBITORE_NEL_GRUPPO
--------------------------------------------------------

  CREATE OR REPLACE NONEDITIONABLE TRIGGER "OOBD16"."TRG_DEBITORE_NEL_GRUPPO" 
BEFORE INSERT OR UPDATE OF idSpesa, emailUtente ON Debito
FOR EACH ROW
DECLARE
    v_id_gruppo_spesa INT;
    v_is_membro        NUMBER;
BEGIN
    SELECT idGruppo 
    INTO v_id_gruppo_spesa
    FROM Spesa
    WHERE idSpesa = :NEW.idSpesa;

    SELECT COUNT(*)
    INTO v_is_membro
    FROM PartecipazioneGruppo
    WHERE idGruppo = v_id_gruppo_spesa 
      AND emailUtente = :NEW.emailUtente
      AND statoInvito = 1; -- Assicuriamoci che l'utente sia attivo nel gruppo

    IF v_is_membro = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20003, 
            'Violazione Vincolo: Impossibile assegnare il debito all''utente ' || :NEW.emailUtente || 
            ' per la spesa #' || :NEW.idSpesa || 
            ' perché non partecipa al gruppo di questa spesa (Gruppo #' || v_id_gruppo_spesa || ').'
        );
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20004, 'Errore: La spesa specificata non esiste.');
END;
/
